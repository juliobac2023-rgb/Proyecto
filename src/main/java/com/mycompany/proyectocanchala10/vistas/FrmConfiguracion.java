    private void guardarConfiguracion() {

        try {
            double dia = leerDecimal(txtDia, "Tarifa de dia");
            double noche = leerDecimal(txtNoche, "Tarifa de noche");
            double fin = leerDecimal(txtFin, "Tarifa de fin de semana");

            // La clase Tarifa valida que las tres sean mayores a 0.
            if (!Tarifa.configurar(dia, noche, fin)) {
                error("Las tarifas deben ser mayores a 0.");
                return;
            }

            configuracion.setModuloTienda(chkTienda.isSelected());

            // Se escribe configuracion.txt y tarifas.csv de una vez.
            ProyectoCanchaLa10.guardar();

            info("Configuracion guardada.\n"
                    + "Las tarifas nuevas aplican a las reservas que se creen "
                    + "desde ahora; las que ya existen conservan su total.\n"
                    + "Modulo de tienda: "
                    + (chkTienda.isSelected() ? "ACTIVADO" : "DESACTIVADO") + ".");

        } catch (IllegalArgumentException e) {
            error(e.getMessage());
        }
    }

