    // tipo 1 = reporte de reservas, tipo 2 = reporte de tienda.
    private void generar(int tipo) {

        try {
            LocalDate desde = leerFecha(txtDesde, "Desde");
            LocalDate hasta = leerFecha(txtHasta, "Hasta");

            if (hasta.isBefore(desde)) {
                error("La fecha final no puede ser antes de la inicial.");
                return;
            }

            if (tipo == 1) {

                // Texto vacio = sin filtro. El combo de canchas empieza
                // con el codigo: "C01 - La Bombonera".
                String cancha = "";
                String estado = "";

                if (cboCancha.getSelectedIndex() > 0) {
                    cancha = ((String) cboCancha.getSelectedItem()).split(" - ")[0];
                }

                if (cboEstado.getSelectedIndex() > 0) {
                    estado = (String) cboEstado.getSelectedItem();
                }

                txtResultado.setText(reportes.resumen(ProyectoCanchaLa10.reservas,
                        canchas, desde, hasta, cancha, estado));

            } else {
                txtResultado.setText(ProyectoCanchaLa10.tienda.reporte(desde, hasta));
            }

            txtResultado.setCaretPosition(0);

        } catch (IllegalArgumentException e) {
            error(e.getMessage());
        }
    }

    // ------------------------------------------------------------ METODOS DE AYUDA

    private void error(String mensaje) {
        javax.swing.JOptionPane.showMessageDialog(this, mensaje, "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE);
    }

    // Acepta AAAA-MM-DD o la palabra "hoy".
    private java.time.LocalDate leerFecha(javax.swing.JTextField campo, String nombre) {
        String t = campo.getText().trim();
        if (t.equalsIgnoreCase("hoy")) {
            return java.time.LocalDate.now();
        }
        try {
            return java.time.LocalDate.parse(t);
        } catch (java.time.format.DateTimeParseException e) {
            campo.requestFocus();
            throw new IllegalArgumentException(nombre + ": fecha no valida. Ejemplo: 2026-12-31");
        }
    }

