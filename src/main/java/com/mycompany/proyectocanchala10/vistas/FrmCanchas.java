    private boolean confirmar(String mensaje) {
        return javax.swing.JOptionPane.showConfirmDialog(this, mensaje, "Confirmar",
                javax.swing.JOptionPane.YES_NO_OPTION) == javax.swing.JOptionPane.YES_OPTION;
    }

    private String leerTexto(javax.swing.JTextField campo) {
        return campo.getText().trim();
    }

    // Si el dato no es valido lanza IllegalArgumentException con un mensaje claro.
    private int leerEntero(javax.swing.JTextField campo, String nombre) {
        try {
            return Integer.parseInt(campo.getText().trim());
        } catch (NumberFormatException e) {
            campo.requestFocus();
            throw new IllegalArgumentException(nombre + ": escribe un numero entero valido.");
        }
    }

    private double leerDecimal(javax.swing.JTextField campo, String nombre) {
        try {
            return Double.parseDouble(campo.getText().trim());
        } catch (NumberFormatException e) {
            campo.requestFocus();
            throw new IllegalArgumentException(nombre + ": escribe un numero valido (ej. 25.50).");
        }
    }

    private java.time.LocalTime leerHora(javax.swing.JTextField campo, String nombre) {
        try {
            return java.time.LocalTime.parse(campo.getText().trim());
        } catch (java.time.format.DateTimeParseException e) {
            campo.requestFocus();
            throw new IllegalArgumentException(nombre + ": hora no valida. Ejemplo: 18:00");
        }
    }

    // Modelo de tabla que no deja editar las celdas con doble clic.
    private DefaultTableModel crearModelo(String... columnas) {
        return new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };
    }

    private void prepararTabla(javax.swing.JTable tabla, DefaultTableModel modelo) {
        tabla.setModel(modelo);
        tabla.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
        tabla.getTableHeader().setReorderingAllowed(false);
        tabla.setRowHeight(24);
    }

