    // Acepta AAAA-MM-DD o la palabra "hoy".
    private java.time.LocalDate leerFecha(javax.swing.JTextField campo, String nombre) {
        String t = campo.getText().trim();
        if (t.equalsIgnoreCase("hoy")) {
            return java.time.LocalDate.now();
        }
        try {
            return java.time.LocalDate.parse(t);
        } catch (java.time.format.DateTimeParseException e) {
            campo.requestFocus();
            throw new IllegalArgumentException(nombre + ": fecha no valida. Ejemplo: 2026-12-31");
        }
    }

    // Modelo de tabla que no deja editar las celdas con doble clic.
    private DefaultTableModel crearModelo(String... columnas) {
        return new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };
    }

