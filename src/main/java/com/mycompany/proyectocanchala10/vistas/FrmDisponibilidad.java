    // Avanza o retrocede la fecha y vuelve a cargar la tabla.
    private void cambiarDia(int dias) {

        try {
            txtFecha.setText(leerFecha(txtFecha, "Fecha").plusDays(dias).toString());
            cargar();
        } catch (IllegalArgumentException e) {
            error(e.getMessage());
        }
    }

    private void cargar() {

        LocalDate fecha;

        try {
            fecha = leerFecha(txtFecha, "Fecha");
        } catch (IllegalArgumentException e) {
            error(e.getMessage());
            return;
        }

        lblDia.setText(nombreDia(fecha) + " " + fecha);

        if (canchas.getCantidad() == 0) {
            return;
        }

        // Columnas: la hora y despues una por cada cancha.
        String[] columnas = new String[canchas.getCantidad() + 1];
        columnas[0] = "Hora";

        // La tabla va desde la apertura mas temprana hasta el cierre mas tarde.
        int primera = 23;
        int ultima = 0;

        for (int i = 0; i < canchas.getCantidad(); i++) {

            Cancha c = canchas.getCanchas()[i];

            columnas[i + 1] = c.getCodigo() + " " + c.getNombre()
                    + " (" + c.getTipo() + ")";

            if (c.getHoraApertura().getHour() < primera) {
                primera = c.getHoraApertura().getHour();
            }

            int cierre = c.getHoraCierre().getHour()
                    + (c.getHoraCierre().getMinute() > 0 ? 1 : 0);

            if (cierre > ultima) {
                ultima = cierre;
            }
        }

        DefaultTableModel modelo = crearModelo(columnas);

        for (int hora = primera; hora < ultima && hora < 24; hora++) {

            LocalTime inicio = LocalTime.of(hora, 0);
            // La ultima hora del dia termina a las 23:59.
            LocalTime fin = hora == 23 ? LocalTime.of(23, 59) : LocalTime.of(hora + 1, 0);

            Object[] fila = new Object[columnas.length];
            fila[0] = inicio + " - " + fin;

            for (int i = 0; i < canchas.getCantidad(); i++) {
                fila[i + 1] = estadoDe(canchas.getCanchas()[i], fecha, inicio, fin);
            }

            modelo.addRow(fila);
        }

        tblHorario.setModel(modelo);
        tblHorario.getColumnModel().getColumn(0).setMinWidth(120);
        tblHorario.getColumnModel().getColumn(0).setMaxWidth(120);
    }

    // Texto de una celda: como esta la cancha en esa hora.
    private String estadoDe(Cancha c, LocalDate fecha, LocalTime inicio, LocalTime fin) {

        if (!c.getEstado().equals("DISPONIBLE")) {
            return c.getEstado();
        }

        if (inicio.isBefore(c.getHoraApertura()) || fin.isAfter(c.getHoraCierre())) {
            return "CERRADA";
        }

        // El gestor aplica la regla de traslape.
        Reserva r = reservas.ocupante(c, fecha, inicio, fin);

        if (r == null) {
            return "LIBRE";
        }

        return "R" + r.getCodigo() + " " + r.getCliente().getNombre()
                + " (" + r.getEstado() + ")";
    }

    private String nombreDia(LocalDate fecha) {

        String[] dias = {"Lunes", "Martes", "Miercoles", "Jueves",
            "Viernes", "Sabado", "Domingo"};

        return dias[fecha.getDayOfWeek().getValue() - 1];
    }

