    // Llena la tabla con los clientes cuyo nombre o telefono
    // contienen lo escrito en el buscador.
    private void cargarTabla() {

        String filtro = leerTexto(txtBuscar).toLowerCase();

        modelo.setRowCount(0);
        cantidadFilas = 0;

        for (int i = 0; i < clientes.getCantidad(); i++) {

            Cliente c = clientes.getClientes()[i];

            // La regla de busqueda (codigo, nombre o telefono) esta en el gestor.
            if (!clientes.coincide(c, filtro)) {
                continue;
            }

            modelo.addRow(new Object[]{
                c.getCodigo(), c.getNombre(), c.getTelefono(),
                c.getCorreo(), c.getFechaRegistro()
            });
            filas[cantidadFilas] = c;
            cantidadFilas++;
        }
    }

    // Pasa los datos de la fila seleccionada al formulario.
    private void seleccionar() {

        int fila = tblClientes.getSelectedRow();

        if (fila < 0) {
            return;
        }

        Cliente c = filas[fila];

        txtCodigo.setText(String.valueOf(c.getCodigo()));
        txtNombre.setText(c.getNombre());
        txtTelefono.setText(c.getTelefono());
        txtCorreo.setText(c.getCorreo());
    }

    private void registrar() {

        if (!txtCodigo.getText().isEmpty()) {
            aviso("Hay un cliente seleccionado. Presiona Limpiar "
                    + "para registrar uno nuevo, o Guardar cambios para editarlo.");
            return;
        }

        Cliente nuevo = clientes.registrar(leerTexto(txtNombre),
                leerTexto(txtTelefono), leerTexto(txtCorreo));

        if (nuevo == null) {
            error("No se pudo registrar: nombre o telefono vacio, "
                    + "telefono ya registrado o limite de clientes alcanzado.");
            return;
        }

        info("Cliente registrado con codigo " + nuevo.getCodigo() + ".");
        limpiar();
    }

    private void editar() {

        if (txtCodigo.getText().isEmpty()) {
            aviso("Primero selecciona un cliente de la tabla.");
            return;
        }

        int codigo = Integer.parseInt(txtCodigo.getText());

        if (clientes.editar(codigo, leerTexto(txtNombre),
                leerTexto(txtTelefono), leerTexto(txtCorreo))) {

            info("Cliente actualizado.");
            limpiar();

        } else {
            error("No se pudo editar: datos vacios "
                    + "o telefono usado por otro cliente.");
        }
    }

    private void limpiar() {

        txtCodigo.setText("");
        txtNombre.setText("");
        txtTelefono.setText("");
        txtCorreo.setText("");
        tblClientes.clearSelection();
        cargarTabla();
        txtNombre.requestFocus();
    }

