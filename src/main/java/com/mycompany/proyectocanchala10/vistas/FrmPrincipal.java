    // Refresca el resumen del dia. Los calculos los hacen los gestores;
    // aqui solo se muestran los resultados.
    private void actualizar() {

        LocalDate hoy = LocalDate.now();

        // El modulo de tienda se activa o desactiva en la configuracion.
        boolean conTienda = ProyectoCanchaLa10.configuracion.isModuloTienda();

        btnTienda.setVisible(conTienda);
        lblTienda.setVisible(conTienda);

        lblHoy.setText("Resumen de hoy (" + hoy + ")");
        lblReservasHoy.setText("Reservas de hoy: " + reservas.contarFecha(hoy));
        lblEnCurso.setText("En curso: " + reservas.contarEstado("EN_CURSO"));
        lblPendientes.setText("Pendientes de confirmar: "
                + reservas.contarEstado("PENDIENTE"));
        lblConSaldo.setText("Reservas con saldo: " + reservas.contarConSaldo());
        lblIngresos.setText("Ingresos de hoy (pagos): "
                + Formato.dinero(reservas.ingresos(hoy, hoy)));
        lblTienda.setText("Ventas de tienda hoy: "
                + Formato.dinero(tienda.ingresosSueltas(hoy, hoy)));

        // Tabla con las reservas de hoy.
        modelo.setRowCount(0);

        for (int i = 0; i < reservas.getCantidad(); i++) {

            Reserva r = reservas.getReservas()[i];

            if (r.getFecha().equals(hoy)) {

                modelo.addRow(new Object[]{
                    r.getInicio() + " - " + r.getFin(),
                    r.getCancha().getNombre(), r.getCliente().getNombre(),
                    r.getEstado(), Formato.dinero(r.getSaldo())
                });
            }
        }
    }

