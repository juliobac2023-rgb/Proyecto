    private void cargarTabla() {

        modelo.setRowCount(0);
        cantidadFilas = 0;

        for (int i = 0; i < reservas.getCantidad(); i++) {

            Reserva r = reservas.getReservas()[i];

            if (filtro == 1 && !r.getFecha().equals(fechaFiltro)) {
                continue;
            }
            if (filtro == 2 && r.getCliente().getCodigo() != clienteFiltro.getCodigo()) {
                continue;
            }

            modelo.addRow(new Object[]{
                "R" + r.getCodigo(), r.getFecha(),
                r.getInicio() + " - " + r.getFin(),
                r.getCancha().getNombre(), r.getCliente().getNombre(),
                r.getEstado(), Formato.dinero(r.getTotal()),
                Formato.dinero(r.getPagado()), Formato.dinero(r.getSaldo())
            });
            filas[cantidadFilas] = r;
            cantidadFilas++;
        }

        if (filtro == 1) {
            lblMostrando.setText("Mostrando: agenda del " + fechaFiltro);
        } else if (filtro == 2) {
            lblMostrando.setText("Mostrando: " + clienteFiltro.getNombre());
        } else {
            lblMostrando.setText("Mostrando: todas");
        }
    }

    // Recarga la tabla y vuelve a seleccionar la reserva r.
    private void refrescar(Reserva r) {

        cargarTabla();

        for (int i = 0; i < cantidadFilas; i++) {

            if (filas[i] == r) {
                tblReservas.setRowSelectionInterval(i, i);
            }
        }
    }

    private Reserva reservaSeleccionada() {

        int fila = tblReservas.getSelectedRow();

        if (fila < 0) {
            aviso("Primero selecciona una reserva de la tabla.");
            return null;
        }

        return filas[fila];
    }

