    private void cargarCanchas() {

        cboCancha.removeAllItems();

        for (int i = 0; i < canchas.getCantidad(); i++) {

            Cancha c = canchas.getCanchas()[i];

            cboCancha.addItem(c.getCodigo() + " - " + c.getNombre()
                    + " (" + c.getTipo() + ")"
                    + (c.getEstado().equals("DISPONIBLE") ? "" : " [" + c.getEstado() + "]"));
        }
    }

    // El texto del combo empieza con el codigo: "C01 - La Bombonera (Futbol 5)".
    private Cancha canchaSeleccionada() {

        String item = (String) cboCancha.getSelectedItem();

        if (item == null) {
            return null;
        }

        return canchas.buscar(item.split(" - ")[0]);
    }

    // Busca el cliente por telefono; si no existe ofrece registrarlo.
    private void buscarCliente() {

        String telefono = leerTexto(txtTelefono);
        clienteActual = null;
        lblCliente.setText("(busca al cliente por telefono)");

        if (telefono.isEmpty()) {
            aviso("Escribe el telefono del cliente.");
            return;
        }

        Cliente c = clientes.buscarTelefono(telefono);

        if (c == null) {

            if (!confirmar("No existe un cliente con ese telefono.\n"
                    + "Registrarlo ahora?")) {
                return;
            }

            JTextField nombre = new JTextField();
            JTextField correo = new JTextField();

            if (!pedirDatos("Nuevo cliente",
                    "Telefono: " + telefono,
                    "Nombre:", nombre,
                    "Correo (opcional):", correo)) {
                return;
            }

            c = clientes.registrar(leerTexto(nombre), telefono, leerTexto(correo));

            if (c == null) {
                error("No se pudo registrar: nombre vacio "
                        + "o limite de clientes alcanzado.");
                return;
            }

            info("Cliente registrado con codigo " + c.getCodigo() + ".");
        }

        clienteActual = c;
        lblCliente.setText(c.getNombre() + " (codigo " + c.getCodigo() + ")");
    }

    // Revisa que el cliente buscado siga siendo el del telefono escrito.
    private boolean clienteValido() {

        if (clienteActual == null
                || !clienteActual.getTelefono().equals(leerTexto(txtTelefono))) {
            buscarCliente();
        }

        return clienteActual != null;
    }

    // Lee fecha, hora de inicio y horas. Lanza IllegalArgumentException si algo esta mal.
    private void leerHorario() {

        fecha = leerFecha(txtFecha, "Fecha");
        inicio = leerHora(txtInicio, "Hora de inicio");
        horas = leerEntero(txtHoras, "Cantidad de horas");
    }

    private void verPrecio() {

        try {
            Cancha cancha = canchaSeleccionada();
            leerHorario();

            if (!reservas.disponible(cancha, fecha, inicio, horas)) {
                lblPrecio.setText("Precio: - (no disponible)");
                aviso("La cancha no esta disponible en ese horario "
                        + "(ocupada, fuera de su horario, en mantenimiento "
                        + "o horas invalidas).");
                return;
            }

            lblPrecio.setText("Precio: " + Formato.dinero(
                    Tarifa.calcular(cancha, fecha, inicio, horas)));

        } catch (IllegalArgumentException e) {
            error(e.getMessage());
        }
    }

    private void reservar() {

        if (!clienteValido()) {
            return;
        }

        try {
            Cancha cancha = canchaSeleccionada();
            leerHorario();

            if (!reservas.disponible(cancha, fecha, inicio, horas)) {
                error("La cancha no esta disponible en ese horario "
                        + "(ocupada, fuera de su horario, en mantenimiento "
                        + "o horas invalidas).");
                return;
            }

            double precio = Tarifa.calcular(cancha, fecha, inicio, horas);
            lblPrecio.setText("Precio: " + Formato.dinero(precio));

            if (!confirmar("Confirmar la reserva?\n\n"
                    + "Cliente: " + clienteActual.getNombre() + "\n"
                    + "Cancha: " + cancha.getNombre() + "\n"
                    + "Fecha: " + fecha + "  de " + inicio + " a " + inicio.plusHours(horas) + "\n"
                    + "Precio total: " + Formato.dinero(precio))) {
                return;
            }

            Reserva r = reservas.registrar(clienteActual, cancha, fecha, inicio, horas);

            if (r == null) {
                error("No se pudo crear la reserva: la fecha u hora "
                        + "ya paso o se alcanzo el limite de reservas.");
                return;
            }

            filtro = 0;
            refrescar(r);

            info("Reserva R" + r.getCodigo() + " creada (PENDIENTE).\n"
                    + "Se confirma al registrar el primer pago.");

            if (confirmar("Registrar un pago ahora?")) {
                pagar(r);
            }

        } catch (IllegalArgumentException e) {
            error(e.getMessage());
        }
    }

    // Muestra las canchas libres de un tipo para la fecha y horario escritos.
    private void disponibilidad() {

        try {
            leerHorario();
        } catch (IllegalArgumentException e) {
            error(e.getMessage());
            return;
        }

        // Tipos de cancha que existen, sin repetir.
        String[] encontrados = new String[canchas.getCantidad()];
        int cantidadTipos = 0;

        for (int i = 0; i < canchas.getCantidad(); i++) {

            String tipoCancha = canchas.getCanchas()[i].getTipo();
            boolean repetido = false;

            for (int j = 0; j < cantidadTipos; j++) {
                if (encontrados[j].equalsIgnoreCase(tipoCancha)) {
                    repetido = true;
                }
            }

            if (!repetido) {
                encontrados[cantidadTipos] = tipoCancha;
                cantidadTipos++;
            }
        }

        if (cantidadTipos == 0) {
            aviso("No hay canchas registradas.");
            return;
        }

        // Arreglo del tamano exacto para mostrarlo en la lista.
        String[] tipos = new String[cantidadTipos];

        for (int i = 0; i < cantidadTipos; i++) {
            tipos[i] = encontrados[i];
        }

        Object tipo = JOptionPane.showInputDialog(this, "Tipo de cancha:",
                "Disponibilidad", JOptionPane.QUESTION_MESSAGE, null,
                tipos, tipos[0]);

        if (tipo == null) {
            return;
        }

        mostrarTexto("Disponibilidad " + fecha + " " + inicio,
                reservas.consultar(canchas, tipo.toString(), fecha, inicio, horas));
    }

    // ------------------------------------------------------------ ACCIONES SOBRE UNA RESERVA

    private void verComprobante() {

        Reserva r = reservaSeleccionada();

        if (r != null) {
            mostrarTexto("Comprobante R" + r.getCodigo(),
                    reservas.comprobante(r));
        }
    }

    private void pagar(Reserva r) {

        if (r == null) {
            return;
        }

        if (r.getSaldo() <= 0) {
            info("La reserva R" + r.getCodigo() + " ya esta pagada completa.");
            return;
        }

        JTextField monto = new JTextField(String.format(Locale.US, "%.2f", r.getSaldo()));
        JComboBox<String> metodo = new JComboBox<>(metodosPago);
        JTextField observacion = new JTextField();

        if (!pedirDatos("Pago de la reserva R" + r.getCodigo(),
                "Total: " + Formato.dinero(r.getTotal())
                + "   Pagado: " + Formato.dinero(r.getPagado())
                + "   Saldo: " + Formato.dinero(r.getSaldo()),
                "Monto a pagar (Q):", monto,
                "Metodo de pago:", metodo,
                "Observacion (opcional):", observacion)) {
            return;
        }

        try {
            double valor = leerDecimal(monto, "Monto");

            if (reservas.pagar(r, valor, (String) metodo.getSelectedItem(),
                    leerTexto(observacion))) {

                info("Pago registrado.\nEstado: " + r.getEstado()
                        + "\nSaldo: " + Formato.dinero(r.getSaldo()));

            } else {
                error("No se pudo registrar el pago: reserva "
                        + "cancelada, monto invalido o mayor al saldo.");
            }

        } catch (IllegalArgumentException e) {
            error(e.getMessage());
        }

        refrescar(r);
    }

    private void agregarServicio() {

        Reserva r = reservaSeleccionada();

        if (r == null) {
            return;
        }

        JTextField nombre = new JTextField();
        JTextField precio = new JTextField();

        if (!pedirDatos("Agregar servicio a R" + r.getCodigo(),
                "Nombre del servicio (ej. Arbitro):", nombre,
                "Precio (Q):", precio)) {
            return;
        }

        try {
            double valor = leerDecimal(precio, "Precio");

            if (leerTexto(nombre).isEmpty() || valor <= 0) {
                error("Nombre vacio o precio invalido.");
                return;
            }

            if (r.agregarServicio(new ServicioAdicional(leerTexto(nombre), valor))) {
                info("Servicio agregado. Nuevo total: "
                        + Formato.dinero(r.getTotal()));
            } else {
                error("No se pudo agregar: la reserva esta "
                        + "cancelada o finalizada, o ya tiene 10 servicios.");
            }

        } catch (IllegalArgumentException e) {
            error(e.getMessage());
        }

        refrescar(r);
    }

    private void cambiarEstado() {

        Reserva r = reservaSeleccionada();

        if (r == null) {
            return;
        }

        Object estado = JOptionPane.showInputDialog(this,
                "Estado actual: " + r.getEstado() + "\nNuevo estado:",
                "Cambiar estado de R" + r.getCodigo(), JOptionPane.QUESTION_MESSAGE,
                null, estadosReserva, estadosReserva[0]);

        if (estado == null) {
            return;
        }

        if (r.cambiarEstado(estado.toString())) {

            info("Estado actualizado a " + estado + ".");

            if (estado.equals("FINALIZADA") && r.getSaldo() > 0) {
                aviso("La reserva termino con saldo pendiente de "
                        + Formato.dinero(r.getSaldo()) + ".");
            }

        } else {
            error("No se pudo cambiar: solo se pasa de "
                    + "CONFIRMADA a EN_CURSO y de EN_CURSO a FINALIZADA.");
        }

        refrescar(r);
    }

    private void cancelar() {

        Reserva r = reservaSeleccionada();

        if (r == null) {
            return;
        }

        if (r.getPagado() > 0) {
            aviso("Esta reserva ya tiene pagos por "
                    + Formato.dinero(r.getPagado())
                    + ".\nEl sistema no maneja devoluciones.");
        }

        JTextField motivo = new JTextField();
        JTextField operador = new JTextField();

        if (!pedirDatos("Cancelar la reserva R" + r.getCodigo(),
                "Motivo de la cancelacion:", motivo,
                "Quien cancela (operador):", operador)) {
            return;
        }

        if (!confirmar("Seguro que deseas cancelar la reserva R"
                + r.getCodigo() + "?")) {
            return;
        }

        if (r.cancelar(leerTexto(motivo), leerTexto(operador), LocalDate.now())) {
            info("Reserva cancelada.");
        } else {
            error("No se pudo cancelar: ya estaba cancelada o "
                    + "finalizada, o falta el motivo o el operador.");
        }

        refrescar(r);
    }

